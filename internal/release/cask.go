package release

import (
	"bytes"
	"errors"
	"fmt"
	"regexp"
	"strings"
)

// repository is the GitHub repository that publishes Rhizome releases.
const repository = "aliengiraffe/rhizome"

// caskArchives lists the goos/goarch archives the cask installs, in template
// order. Windows has no Homebrew.
var caskArchives = []string{"darwin/all", "linux/arm64", "linux/amd64"}

// caskVersion finds the version stanza of a rendered cask.
var caskVersion = regexp.MustCompile(`(?m)^  version "([^"]+)"$`)

// RenderCask verifies the release assets in dir against their checksum
// manifest, exactly as publish does, and renders the Homebrew cask for the
// stable release v from the manifest's digests. Prereleases and snapshots
// never get a cask.
func RenderCask(dir string, v Version) ([]byte, error) {
	if v.Tag == "" {
		return nil, errors.New("snapshots have no Homebrew cask")
	}
	if v.IsPrerelease() {
		return nil, fmt.Errorf("prerelease %s has no Homebrew cask", v.Tag)
	}
	sums, err := verifiedSums(dir, v.AssetVersion(), true)
	if err != nil {
		return nil, err
	}
	return renderCask(v, sums)
}

func renderCask(v Version, sums map[string]string) ([]byte, error) {
	// Homebrew treats a URL without #{version} as unversioned. The tag is
	// always an optional "v" plus the version; the asset version differs
	// when build metadata turns "+" into ".", and then stays literal.
	tag := strings.Replace(v.Tag, v.Version, "#{version}", 1)
	asset := v.AssetVersion()
	if asset == v.Version {
		asset = "#{version}"
	}
	args := []any{v.Version}
	for _, p := range caskArchives {
		goos, goarch, _ := strings.Cut(p, "/")
		name := ArchiveName(v.AssetVersion(), goos, goarch)
		sum, ok := sums[name]
		if !ok {
			return nil, fmt.Errorf("checksum manifest has no entry for %s", name)
		}
		url := fmt.Sprintf("https://github.com/%s/releases/download/%s/%s", repository, tag, ArchiveName(asset, goos, goarch))
		args = append(args, sum, url)
	}
	return fmt.Appendf(nil, caskTemplate, args...), nil
}

// caskTemplate is the generated cask. The universal darwin archive serves
// both Mac architectures, so on_macos needs no on_arm/on_intel split. There
// is no postflight and no zap: Homebrew never starts, stops or reinstalls the
// observer service and never touches ~/.rhizome.
const caskTemplate = `# This file was generated by the Rhizome release pipeline. DO NOT EDIT.
# Source: https://github.com/aliengiraffe/rhizome/blob/main/internal/release/cask.go
cask "rhizome" do
  version "%s"

  on_macos do
    sha256 "%s"

    url "%s"
  end
  on_linux do
    on_arm do
      sha256 "%s"
      url "%s"
    end
    on_intel do
      sha256 "%s"
      url "%s"
    end
  end

  name "Rhizome"
  desc "Connect coding agent sessions across terminals and machines"
  homepage "https://github.com/aliengiraffe/rhizome"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "rhizome"

  caveats <<~EOS
    Run rhizome setup to register Rhizome with your coding agents.

    After an upgrade, a running observer service keeps the old binary until
    you restart it:
      rhizome service stop
      rhizome service start
    Restart your coding agents so their MCP servers use the new binary too.

    On Linux, the service and agent registrations record this version's
    Caskroom path, so after each upgrade run:
      rhizome service uninstall
      rhizome service install
      rhizome setup --agents
  EOS
end
`

// CaskSuperseded reports whether the existing cask already installs a newer
// release than v, so a re-run for an older tag never downgrades the tap. An
// empty current cask supersedes nothing; one without a valid version fails
// closed.
func CaskSuperseded(current []byte, v Version) (bool, error) {
	if len(bytes.TrimSpace(current)) == 0 {
		return false, nil
	}
	if !bytes.HasPrefix(current, []byte(caskTemplate[:strings.IndexByte(caskTemplate, '\n')])) {
		return false, errors.New("existing cask was not generated by the release pipeline; refusing to replace it")
	}
	found := caskVersion.FindAllSubmatch(current, -1)
	if len(found) != 1 {
		return false, fmt.Errorf("existing cask has %d version stanzas, want 1", len(found))
	}
	cur, err := ParseTag(string(found[0][1]))
	if err != nil {
		return false, fmt.Errorf("existing cask version: %w", err)
	}
	return compareCore(cur, v) > 0, nil
}

// compareCore orders versions by MAJOR.MINOR.PATCH. Casks only ever hold
// stable releases, and build metadata carries no precedence.
func compareCore(a, b Version) int {
	for _, d := range [][2]uint64{{a.Major, b.Major}, {a.Minor, b.Minor}, {a.Patch, b.Patch}} {
		switch {
		case d[0] < d[1]:
			return -1
		case d[0] > d[1]:
			return 1
		}
	}
	return 0
}
