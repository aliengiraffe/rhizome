// releaseDir writes fake assets and their manifest for tag and returns the
// directory and the manifest's digests.
func releaseDir(t *testing.T, tag string) (string, Version, map[string]string) {
	t.Helper()
	v, err := ParseTag(tag)
	if err != nil {
		t.Fatal(err)
	}
	dir := writeAssets(t, v.AssetVersion())
	if err := WriteManifest(dir, v.AssetVersion()); err != nil {
		t.Fatal(err)
	}
	sums, err := verifiedSums(dir, v.AssetVersion(), true)
	if err != nil {
		t.Fatal(err)
	}
	return dir, v, sums
}

func TestRenderCask(t *testing.T) {
	tests := []struct {
		tag, version, base, asset string
	}{
		{"v1.2.3", "1.2.3", "https://github.com/aliengiraffe/rhizome/releases/download/v#{version}/", "#{version}"},
		{"1.2.3", "1.2.3", "https://github.com/aliengiraffe/rhizome/releases/download/#{version}/", "#{version}"},
		// Build metadata alone is stable; asset names replace "+" with ".".
		{"v2.0.0+build.5", "2.0.0+build.5", "https://github.com/aliengiraffe/rhizome/releases/download/v#{version}/", "2.0.0.build.5"},
	}
	for _, tt := range tests {
		t.Run(tt.tag, func(t *testing.T) {
			dir, v, sums := releaseDir(t, tt.tag)
			out, err := RenderCask(dir, v)
			if err != nil {
				t.Fatal(err)
			}
			cask := string(out)
			sum := func(goos, goarch string) string { return sums[ArchiveName(v.AssetVersion(), goos, goarch)] }
			for _, want := range []string{
				"# This file was generated by the Rhizome release pipeline. DO NOT EDIT.\n",
				"cask \"rhizome\" do\n  version \"" + tt.version + "\"\n",
				"  on_macos do\n    sha256 \"" + sum("darwin", "all") + "\"\n\n" +
					"    url \"" + tt.base + "rhizome_" + tt.asset + "_darwin_all.tar.gz\"\n  end\n",
				"    on_arm do\n      sha256 \"" + sum("linux", "arm64") + "\"\n" +
					"      url \"" + tt.base + "rhizome_" + tt.asset + "_linux_arm64.tar.gz\"\n    end\n",
				"    on_intel do\n      sha256 \"" + sum("linux", "amd64") + "\"\n" +
					"      url \"" + tt.base + "rhizome_" + tt.asset + "_linux_amd64.tar.gz\"\n    end\n",
				"  binary \"rhizome\"\n",
				"      rhizome service stop\n      rhizome service start\n",
			} {
				if !strings.Contains(cask, want) {
					t.Errorf("cask lacks %q:\n%s", want, cask)
				}
			}
			// The universal archive is the only Mac download, and the cask
			// never ships Windows, the package, hooks that run the binary or
			// a zap that would remove ~/.rhizome.
			for _, banned := range []string{"windows", ".pkg", "postflight", "preflight", "uninstall_", "zap", "%!"} {
				if strings.Contains(cask, banned) {
					t.Errorf("cask contains %q:\n%s", banned, cask)
				}
			}
			if n := strings.Count(cask, "sha256 "); n != 3 {
				t.Errorf("cask has %d sha256 stanzas, want 3", n)
			}
			if superseded, err := CaskSuperseded(out, v); err != nil || superseded {
				t.Errorf("CaskSuperseded(own render) = %t, %v", superseded, err)
			}
		})
	}
}

func TestRenderCaskRejects(t *testing.T) {
	snapshot, err := Snapshot("0123456789abcdef")
	if err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name, tag, want string
		v               *Version
		mutate          func(t *testing.T, dir string, v Version)
	}{
		{name: "prerelease", tag: "v1.3.0-rc.1", want: "prerelease"},
		{name: "prerelease with build", tag: "v1.3.0-rc.1+build.5", want: "prerelease"},
		{name: "snapshot", tag: "v1.2.3", v: &snapshot, want: "snapshot"},
		{name: "missing manifest entry", tag: "v1.2.3", want: "missing rhizome_1.2.3_linux_arm64.tar.gz",
			mutate: func(t *testing.T, dir string, v Version) {
				rewriteManifest(t, dir, v, func(line string) string {
					if strings.HasSuffix(line, "_linux_arm64.tar.gz") {
						return ""
					}
					return line
				})
			}},
		{name: "mismatched digest", tag: "v1.2.3", want: "does not match manifest",
			mutate: func(t *testing.T, dir string, v Version) {
				name := ArchiveName(v.AssetVersion(), "darwin", "all")
				if err := os.WriteFile(filepath.Join(dir, name), []byte("tampered"), 0o644); err != nil {
					t.Fatal(err)
				}
			}},
		{name: "missing manifest", tag: "v1.2.3", want: "no such file",
			mutate: func(t *testing.T, dir string, v Version) {
				if err := os.Remove(filepath.Join(dir, ManifestName(v.AssetVersion()))); err != nil {
					t.Fatal(err)
				}
			}},
		{name: "stray file", tag: "v1.2.3", want: "unexpected file",
			mutate: func(t *testing.T, dir string, v Version) {
				if err := os.WriteFile(filepath.Join(dir, "rhizome.rb"), nil, 0o644); err != nil {
					t.Fatal(err)
				}
			}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir, v, _ := releaseDir(t, tt.tag)
			if tt.v != nil {
				v = *tt.v
			}
			if tt.mutate != nil {
				tt.mutate(t, dir, v)
			}
			out, err := RenderCask(dir, v)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("RenderCask = %q, %v; want error containing %q", out, err, tt.want)
			}
		})
	}
}

func rewriteManifest(t *testing.T, dir string, v Version, edit func(string) string) {
	t.Helper()
	path := filepath.Join(dir, ManifestName(v.AssetVersion()))
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, line := range strings.Split(strings.TrimSuffix(string(data), "\n"), "\n") {
		if line = edit(line); line != "" {
			out = append(out, line)
		}
	}
	if err := os.WriteFile(path, []byte(strings.Join(out, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestRenderCaskRequiresEveryArchive(t *testing.T) {
	_, v, sums := releaseDir(t, "v1.2.3")
	delete(sums, ArchiveName(v.AssetVersion(), "linux", "amd64"))
	if _, err := renderCask(v, sums); err == nil || !strings.Contains(err.Error(), "linux_amd64") {
		t.Fatalf("renderCask without linux/amd64: %v", err)
	}
}

func TestCaskSuperseded(t *testing.T) {
	render := func(tag string) []byte {
		t.Helper()
		_, v, sums := releaseDir(t, tag)
		out, err := renderCask(v, sums)
		if err != nil {
			t.Fatal(err)
		}
		return out
	}
	tests := []struct {
		name    string
		current []byte
		tag     string
		want    bool
		err     string
	}{
		{name: "no cask yet", current: nil, tag: "v1.2.3"},
		{name: "older cask", current: render("v1.2.2"), tag: "v1.2.3"},
		{name: "same release rerun", current: render("v1.2.3"), tag: "v1.2.3"},
		{name: "same core with build", current: render("v1.2.3"), tag: "v1.2.3+build.5"},
		{name: "newer patch", current: render("v1.2.4"), tag: "v1.2.3", want: true},
		{name: "newer minor", current: render("v1.3.0"), tag: "v1.2.9", want: true},
		{name: "newer major", current: render("v2.0.0"), tag: "v1.9.9", want: true},
		{name: "older major", current: render("v1.9.9"), tag: "v2.0.0"},
		{name: "hand written", current: []byte("cask \"rhizome\" do\n  version \"9.9.9\"\nend\n"), tag: "v1.2.3", err: "not generated"},
		{name: "no version", current: []byte(strings.Replace(string(render("v1.2.3")), "  version ", "  # ", 1)), tag: "v1.2.3", err: "0 version stanzas"},
		{name: "bad version", current: []byte(strings.Replace(string(render("v1.2.3")), "\"1.2.3\"", "\"latest\"", 1)), tag: "v1.2.3", err: "existing cask version"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			v, err := ParseTag(tt.tag)
			if err != nil {
				t.Fatal(err)
			}
			got, err := CaskSuperseded(tt.current, v)
			if tt.err != "" {
				if err == nil || !strings.Contains(err.Error(), tt.err) {
					t.Fatalf("CaskSuperseded = %t, %v; want error containing %q", got, err, tt.err)
				}
				return
			}
			if err != nil || got != tt.want {
				t.Fatalf("CaskSuperseded = %t, %v; want %t", got, err, tt.want)
			}
		})
	}
}
